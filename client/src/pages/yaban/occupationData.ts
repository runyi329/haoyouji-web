const _seen = new Set<string>();
export const OCCUPATIONS = OCCUPATION_LIST.filter(o => {
  if (_seen.has(o)) return false;
  _seen.add(o);
  return true;
});

/**
 * 模糊搜索：支持汉字包含匹配
 * 输入「厨」可匹配「厨师」「中餐厨师」「西餐厨师」等
 */
export function searchOccupations(query: string, limit = 20): string[] {
  if (!query.trim()) return [];
  const q = query.trim();
  const results: Array<{ item: string; score: number }> = [];
  for (const item of OCCUPATIONS) {
    if (item.includes(q)) {
      // 完全包含：按匹配位置打分（越靠前越高）
      const idx = item.indexOf(q);
      const score = idx === 0 ? 100 : 80 - idx;
      results.push({ item, score });
    }
  }
  // 按分数降序，取前 limit 条
  results.sort((a, b) => b.score - a.score);
  return results.slice(0, limit).map(r => r.item);
}
